// Builds the benchmark inputs and the Dart const file from one source of truth.
// Run: node spike/md-bench/gen_inputs.cjs
const fs = require('node:fs');
const path = require('node:path');

const root = path.resolve(__dirname, '..');
const inputDir = path.join(root, 'inputs');
fs.mkdirSync(inputDir, {recursive: true});

const P0_BLOCK =
  '## Section\n\n' +
  'Some **bold**, *italic*, `code`, and a [link](https://example.com) ' +
  'in a paragraph of ordinary prose.\n\n' +
  '- item one\n- item two with ~~strike~~\n\n> quoted line\n\n' +
  '```dart\nfinal x = 1;\n```\n\n' +
  '| a | b |\n| --- | --- |\n| 1 | 2 |\n\n';
const P0_87 =
  'Hello **world** and *friends*, see `code` [link](https://example.com). Plain text test.';

// The S0 corrected sample, copied verbatim from
// refs/heads/worktree-agent-acfa208a26ae27e64@e122680
// clients/mica_flutter/test/support/markdown_bench_inputs.dart
const refPath = path.join(root, 's0_inputs_ref.dart');
const refSrc = fs.readFileSync(refPath, 'utf8');
const sampleStart = refSrc.indexOf("r'''") + 4;
const sampleEnd = refSrc.indexOf("''';", sampleStart);
const S0_SAMPLE = refSrc.slice(sampleStart, sampleEnd);
const hotStart = refSrc.lastIndexOf("'Hot paths:");
const hotEnd = refSrc.indexOf("';", hotStart);
const S0_HOT87 = refSrc.slice(hotStart + 1, hotEnd);

function repeatTo(unit, target) {
  let out = '';
  while (out.length < target) out += unit;
  // Mirrors Rust `sized()`: cut at the last newline inside the target window.
  const cut = out.slice(0, target).lastIndexOf('\n');
  if (cut >= 0) out = out.slice(0, cut + 1);
  return out;
}

// The P0 runs used an exact-character cut, not a line-boundary one. Keeping
// those bytes is what makes this round comparable with the recorded P0.
function exactRepeat(unit, target) {
  let out = '';
  while (out.length < target) out += unit;
  return out.slice(0, target);
}

const files = {
  'p0_87.md': P0_87,
  'p0_10k.md': exactRepeat(P0_BLOCK, 10000),
  'p0_100k.md': exactRepeat(P0_BLOCK, 100000),
  's0_87.md': S0_HOT87,
  's0_sample.md': S0_SAMPLE,
  's0_10k.md': repeatTo(S0_SAMPLE, 10000),
  's0_100k.md': repeatTo(S0_SAMPLE, 100000),
};
for (const [name, text] of Object.entries(files)) {
  fs.writeFileSync(path.join(inputDir, name), text);
}

const dartMap = Object.fromEntries(
  Object.entries(files).map(([name, text]) => [name.replace(/\.md$/, ''), text]),
);
// JSON is a near-subset of Dart string syntax; the one gap is `$`, which Dart
// treats as interpolation. JSON.stringify never emits `\$`, so escaping every
// `$` is safe and leaves all other escapes valid Dart.
const dartLiteral = JSON.stringify(dartMap, null, 2).replace(/\$/g, '\\$');
const dart = '// GENERATED by spike/md-bench/gen_inputs.cjs — do not edit.\n' +
  '// Same bytes as spike/inputs/*.md, which the Rust golden test reads.\n' +
  'const Map<String, String> benchInputs = ' + dartLiteral + ';\n';
fs.writeFileSync(path.join(__dirname, 'inputs.g.dart'), dart);

